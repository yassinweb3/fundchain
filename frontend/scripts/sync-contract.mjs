import { readFileSync, writeFileSync } from "node:fs";
import { Interface, keccak256, toUtf8Bytes } from "ethers";

const artifact = JSON.parse(readFileSync(new URL("../../out/Crowdfunding.sol/Crowdfunding.json", import.meta.url), "utf8"));
const source = readFileSync(new URL("../../src/Crowdfunding.sol", import.meta.url), "utf8");
if (artifact.metadata.compiler.version.split("+")[0] !== "0.8.36" ||
    artifact.metadata.settings.evmVersion !== "osaka" ||
    artifact.metadata.settings.optimizer.enabled || artifact.metadata.settings.viaIR ||
    artifact.metadata.sources["src/Crowdfunding.sol"].keccak256 !== keccak256(toUtf8Bytes(source))) {
  throw new Error("Artifact does not match the current source and pinned compiler settings. Run forge build in WSL.");
}
const output = "// Generated by npm run contract:sync from the pinned Foundry artifact. Do not edit.\n" +
  "export const CONTRACT_ABI = " + JSON.stringify(new Interface(artifact.abi).format(false), null, 2) + " as const;\n" +
  "export const EXPECTED_RUNTIME_HASH = " + JSON.stringify(keccak256(artifact.deployedBytecode.object)) + ";\n";
const destination = new URL("../src/contract.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== output) {
    throw new Error("Frontend ABI/runtime hash is stale. Run npm run contract:sync.");
  }
  console.log("Frontend ABI and runtime hash match the current Solidity artifact.");
} else {
  writeFileSync(destination, output);
}
